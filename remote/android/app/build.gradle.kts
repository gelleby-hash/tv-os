// The launchers the app knows: launchers.properties beside this project (git-ignored, the owner's own addresses),
// else launchers.example.properties. They become Settings.PLACES (BuildConfig.LAUNCHERS) and the hosts the network
// security config lets the app reach in the clear, so the two lists cannot drift apart.
val launchersFile = rootProject.file("launchers.properties").takeIf { it.exists() }
    ?: rootProject.file("launchers.example.properties")
val launchers: List<Pair<String, String>> = run {
    val props = Properties().apply { launchersFile.reader(Charsets.UTF_8).use { load(it) } }
    val keys = props.stringPropertyNames().filter { Regex("""launcher\.\d+""").matches(it) }
        .sortedBy { it.substringAfter('.').toInt() }
    if (keys.isEmpty()) throw GradleException("$launchersFile: no launcher.<number>=<name>|<host>:<port> lines.")
    keys.map { key ->
        val value = props.getProperty(key).trim()
        val match = Regex("""([A-Za-z0-9 ()-]+)\|([A-Za-z0-9.-]+):(\d{1,5})""").matchEntire(value)
        val port = match?.groupValues?.get(3)?.toInt()
        if (match == null || port !in 1..65535)
            throw GradleException("$launchersFile: $key must be <name>|<host>:<port>, not '$value'.")
        match.groupValues[1].trim() to "${match.groupValues[2]}:$port"
    }
}

/** Writes res/xml/network_security_config.xml: unencrypted traffic to the launchers' hosts and loopback only. */
abstract class LauncherNetworkConfig : DefaultTask() {
    @get:Input
    abstract val hosts: ListProperty<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun write() {
        val domains = hosts.get().joinToString("\n") { "        <domain includeSubdomains=\"false\">$it</domain>" }
        val file = outputDir.get().asFile.resolve("xml/network_security_config.xml")
        file.parentFile.mkdirs()
        file.writeText(
            """
            |<?xml version="1.0" encoding="utf-8"?>
            |<!-- Generated by app/build.gradle.kts from launchers.properties. The launcher's WebSocket is plain ws:// on
            |     the home network; unencrypted traffic is allowed to these hosts only. -->
            |<network-security-config>
            |    <base-config cleartextTrafficPermitted="false" />
            |    <domain-config cleartextTrafficPermitted="true">
            |$domains
            |    </domain-config>
            |</network-security-config>
            |""".trimMargin()
        )
    }
}

val launcherNetworkConfig = tasks.register<LauncherNetworkConfig>("launcherNetworkConfig") {
    hosts.set((launchers.map { it.second.substringBefore(':') } + "127.0.0.1").distinct())
    outputDir.set(layout.buildDirectory.dir("generated/launcherRes"))
}

